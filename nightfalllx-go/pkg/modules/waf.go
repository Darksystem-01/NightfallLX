// WAFProfile is an exported view of a known WAF and its recommended evasion
// flags.
type WAFProfile struct {
	Name        string   `json:"name"`
	Vendor      string   `json:"vendor"`
	BypassFlags []string `json:"bypass_flags"`
}

var wafByName = func() map[string]wafSignature {
	m := make(map[string]wafSignature, len(wafSignatures))
	for _, sig := range wafSignatures {
		m[sig.Name] = sig
	}
	return m
}()

// LookupWAFProfile returns the fingerprint profile for a detected WAF name.
func LookupWAFProfile(name string) (WAFProfile, bool) {
	sig, ok := wafByName[name]
	if !ok {
		return WAFProfile{}, false
	}
	return WAFProfile{Name: sig.Name, Vendor: sig.Vendor, BypassFlags: append([]string(nil), sig.BypassFlags...)}, true
}

// RecommendedBypassFlags returns the flags suggested for a WAF name.
func RecommendedBypassFlags(name string) []string {
	if p, ok := LookupWAFProfile(name); ok {
		return p.BypassFlags
	}
	return nil
}

func (m *WAFModule) Run(target *Target, c *client.Client) ([]*Finding, error) {
	var findings []*Finding

	// Send normal request
	resp, err := c.Request("GET", target.URL, "", nil)
	if err != nil || resp == nil {
		return nil, err
	}

	// Send a generic suspicious probe to trigger WAF if silent
	wafProbeURL := target.BuildURLWithParam("waf_probe", "<script>alert('waf_test')</script>' OR 1=1--")
	probeResp, _ := c.Request("GET", wafProbeURL, "", nil)

	responses := []*client.Response{resp}
	if probeResp != nil {
		responses = append(responses, probeResp)
	}

	detectedWAFs := make(map[string]string)

	for _, r := range responses {
		// 1. Check response headers and cookies
		for hName, hVals := range r.Headers {
			hNameLower := strings.ToLower(hName)
			hValStr := strings.ToLower(strings.Join(hVals, " "))

			for _, sig := range wafSignatures {
				for _, h := range sig.Headers {
					if strings.Contains(hNameLower, h) || strings.Contains(hValStr, h) {
						detectedWAFs[sig.Name] = fmt.Sprintf("Header match: %s: %s", hName, strings.TrimSpace(hValStr))
					}
				}
				for _, cookie := range sig.Cookies {
					if strings.Contains(hValStr, cookie) {
						detectedWAFs[sig.Name] = fmt.Sprintf("Cookie indicator: '%s'", cookie)
					}
				}
			}
		}

		// 2. Check response body tokens
		bodyLower := strings.ToLower(r.Body)
		for _, sig := range wafSignatures {
			for _, token := range sig.BodyTokens {
				if strings.Contains(bodyLower, token) {
					detectedWAFs[sig.Name] = fmt.Sprintf("Body indicator: '%s'", token)
				}
			}
		}
	}

	names := make([]string, 0, len(detectedWAFs))
	for name := range detectedWAFs {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, wafName := range names {
		evidence := detectedWAFs[wafName]
		profile, _ := LookupWAFProfile(wafName)
		flags := strings.Join(profile.BypassFlags, " ")

		findings = append(findings, &Finding{
			Module:     m.Name(),
			Title:      fmt.Sprintf("WAF / Reverse Proxy Detected (%s)", wafName),
			Severity:   SeverityInfo,
			Confidence: 95,
			URL:        target.URL,
			Parameter:  "Network Stack",
			Payload:    "Passive / Probe Fingerprint",
			Detail: fmt.Sprintf("Target is protected by %s (%s). Recommended bypass flags: %s",
				wafName, profile.Vendor, flags),
			Evidence:    evidence,
			Remediation: "Information finding only. Ensure WAF rules are tuned to prevent legitimate bypasses.",
			CWEID:       200,
		})
	}

	return findings, nil
}
