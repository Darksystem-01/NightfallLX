package modules

import (
	"fmt"
	"nightfalllx/pkg/client"
	"strings"
)

type WAFModule struct{}

func NewWAFModule() *WAFModule {
	return &WAFModule{}
}

func (m *WAFModule) Name() string {
	return "waf"
}

func (m *WAFModule) Description() string {
	return "Web Application Firewall (WAF) & Reverse Proxy fingerprinter"
}

type wafSignature struct {
	Name       string
	Headers    []string
	BodyTokens []string
}

var wafSignatures = []wafSignature{
	{
		Name:       "Cloudflare",
		Headers:    []string{"cf-ray", "cf-cache-status", "cf-mitigated"},
		BodyTokens: []string{"cloudflare", "checking your browser", "attention required", "cf-chl"},
	},
	{
		Name:       "AWS WAF",
		Headers:    []string{"x-amzn-requestid", "x-amzn-waf-action", "x-amz-cf-id"},
		BodyTokens: []string{"awswaf", "request blocked"},
	},
	{
		Name:       "ModSecurity / OWASP CRS",
		Headers:    []string{"x-modsecurity", "mod_security"},
		BodyTokens: []string{"modsecurity", "this error was generated by mod_security", "web application firewall"},
	},
	{
		Name:       "Akamai",
		Headers:    []string{"x-akamai-transformed", "akamai-origin-hop"},
		BodyTokens: []string{"akamai", "access denied - akamai"},
	},
	{
		Name:       "Imperva / Incapsula",
		Headers:    []string{"x-iinfo", "x-cdn"},
		BodyTokens: []string{"incapsula", "incident id", "_Incapsula_Resource"},
	},
	{
		Name:       "F5 BIG-IP ASM",
		Headers:    []string{"x-wa-info", "bigip"},
		BodyTokens: []string{"the requested url was rejected", "please consult with your administrator"},
	},
}

func (m *WAFModule) Run(target *Target, c *client.Client) ([]*Finding, error) {
	var findings []*Finding

	// Send normal request
	resp, err := c.Request("GET", target.URL, "", nil)
	if err != nil || resp == nil {
		return nil, err
	}

	// Send a generic suspicious probe to trigger WAF if silent
	wafProbeURL := target.BuildURLWithParam("waf_probe", "<script>alert('waf_test')</script>' OR 1=1--")
	probeResp, _ := c.Request("GET", wafProbeURL, "", nil)

	responses := []*client.Response{resp}
	if probeResp != nil {
		responses = append(responses, probeResp)
	}

	detectedWAFs := make(map[string]string)

	for _, r := range responses {
		// 1. Check response headers
		for hName, hVals := range r.Headers {
			hNameLower := strings.ToLower(hName)
			hValStr := strings.ToLower(strings.Join(hVals, " "))

			for _, sig := range wafSignatures {
				for _, h := range sig.Headers {
					if strings.Contains(hNameLower, h) || strings.Contains(hValStr, h) {
						detectedWAFs[sig.Name] = fmt.Sprintf("Header match: %s: %s", hName, hValStr)
					}
				}
			}
		}

		// 2. Check response body tokens
		bodyLower := strings.ToLower(r.Body)
		for _, sig := range wafSignatures {
			for _, token := range sig.BodyTokens {
				if strings.Contains(bodyLower, token) {
					detectedWAFs[sig.Name] = fmt.Sprintf("Body indicator: '%s'", token)
				}
			}
		}
	}

	for wafName, evidence := range detectedWAFs {
		findings = append(findings, &Finding{
			Module:      m.Name(),
			Title:       fmt.Sprintf("WAF / Reverse Proxy Detected (%s)", wafName),
			Severity:    SeverityInfo,
			Confidence:  95,
			URL:         target.URL,
			Parameter:   "Network Stack",
			Payload:     "Passive / Probe Fingerprint",
			Detail:      fmt.Sprintf("Target is protected by %s. Payload mutations and evasion techniques may be needed.", wafName),
			Evidence:    evidence,
			Remediation: "Information finding only. Ensure WAF rules are tuned to prevent legitimate bypasses.",
			CWEID:       200,
		})
	}

	return findings, nil
}
